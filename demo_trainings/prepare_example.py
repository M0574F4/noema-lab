def _capture_readiness_summary(jobs: list[Dict[str, Any]]) -> str:
    order = {"train": 0, "validation": 1, "test": 2}
    rows = []
    for item in sorted(
        (job for job in jobs if isinstance(job, Mapping)),
        key=lambda job: order.get(str(job.get("split") or ""), 99),
    ):
        split = str(item.get("split") or "")
        label = str(item.get("label") or split.replace("_", " ").title())
        requested = int(item.get("requested_samples") or 0)
        if requested > 0:
            rows.append("%s %s" % (label, format(requested, ",d")))
    return " · ".join(rows)


def _bundle_captures_are_ready(
    bundle: Path,
    jobs: list[Dict[str, Any]],
) -> bool:
    """Recognize complete bundle-owned captures after an in-place refresh."""

    required = {"train", "validation", "test"}
    seen = set()
    for job in jobs:
        if not isinstance(job, Mapping):
            continue
        split = str(job.get("split") or "")
        if split not in required:
            continue
        schema_path = Path(bundle) / "data" / split / "schema.json"
        if not schema_path.is_file():
            return False
        try:
            schema = load_strict_yaml_or_json(schema_path)
        except (OSError, UnicodeError, ValueError):
            return False
        if not isinstance(schema, Mapping):
            return False
        requested = int(job.get("requested_samples") or 0)
        if requested and int(schema.get("captured_samples") or 0) < requested:
            return False
        tap_schemas = schema.get("tap_schemas")
        if not isinstance(tap_schemas, Mapping):
            return False
        present_ids = {str(value) for value in tap_schemas}
        present_references = {
            str(value.get("from"))
            for value in tap_schemas.values()
            if isinstance(value, Mapping) and value.get("from")
        }
        for tap in job.get("expected_taps") or []:
            if not isinstance(tap, Mapping):
                continue
            tap_id = str(tap.get("id") or "")
            reference = str(tap.get("from") or "")
            if tap_id not in present_ids and reference not in present_references:
                return False
        seen.add(split)
    return seen == required


