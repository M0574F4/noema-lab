def _load_manifest(bundle):
    path = bundle / "project_manifest.yaml"
    if not path.is_file():
        return {}
    try:
        payload = load_strict_yaml_or_json(path)
    except Exception as exc:
        print(
            "Cannot read the training-bundle manifest: %s" % exc,
            file=sys.stderr,
        )
        return None
    return payload if isinstance(payload, dict) else {}


def _capture_jobs(manifest):
    jobs = manifest.get("capture_jobs") or []
    if jobs:
        return [item for item in jobs if isinstance(item, dict)]
    scaffold = (
        ((manifest.get("external_training") or {}).get("optional_demo_scaffold") or {})
    )
    return [
        item
        for item in (scaffold.get("capture_jobs") or [])
        if isinstance(item, dict)
    ]


def _bundle_path(bundle, manifest, configured, fallback):
    raw_value = str(configured or "").strip()
    if not raw_value:
        return bundle / fallback
    value = Path(raw_value)
    out_dir = Path(str(manifest.get("out_dir") or ""))
    if str(value) and str(out_dir):
        try:
            return bundle / value.relative_to(out_dir)
        except ValueError:
            pass
    if str(value) and not value.is_absolute() and len(value.parts) <= 2:
        return bundle / value
    return bundle / fallback


def _returned_artifact_path(bundle, manifest):
    scaffold = (
        ((manifest.get("external_training") or {}).get("optional_demo_scaffold") or {})
    )
    training = scaffold.get("training") or {}
    configured = training.get("artifact_manifest_path")
    if not configured:
        for item in manifest.get("trained_artifacts") or []:
            if isinstance(item, dict) and item.get("manifest_path"):
                configured = item.get("manifest_path")
                break
    return _bundle_path(
        bundle,
        manifest,
        configured,
        Path("trained_artifact.yaml"),
    )


def _capture_schema_path(bundle, manifest, job, split):
    directory = _bundle_path(
        bundle,
        manifest,
        job.get("output_dir"),
        Path("data") / split,
    )
    return directory / "schema.json"


def _expected_tap_labels(job):
    labels = []
    for tap in job.get("expected_taps") or []:
        if not isinstance(tap, dict):
            continue
        label = str(tap.get("from") or tap.get("id") or "").strip()
        if label and label not in labels:
            labels.append(label)
    return labels


def _missing_taps(schema, job):
    tap_schemas = schema.get("tap_schemas") or {}
    if not isinstance(tap_schemas, dict):
        tap_schemas = {}
    present_ids = set(str(value) for value in tap_schemas)
    present_references = set()
    for value in tap_schemas.values():
        if isinstance(value, dict) and value.get("from"):
            present_references.add(str(value.get("from")))
    missing = []
    for tap in job.get("expected_taps") or []:
        if not isinstance(tap, dict):
            continue
        tap_id = str(tap.get("id") or "")
        reference = str(tap.get("from") or "")
        if tap_id not in present_ids and reference not in present_references:
            missing.append(reference or tap_id)
    return missing


def _capture_preflight(bundle, manifest, target_name):
    required_splits = (
        ("test",) if target_name == "evaluate.py" else ("train", "validation")
    )
    jobs = _capture_jobs(manifest)
    if not jobs:
        return True
    by_split = {str(item.get("split") or ""): item for item in jobs}
    requirements = []
    problems = []
    for split in required_splits:
        job = by_split.get(split)
        if job is None:
            problems.append("%s capture job is missing from project_manifest.yaml" % split)
            continue
        label = str(job.get("label") or split.replace("_", " ").title())
        expected = int(job.get("requested_samples") or 0)
        unit = str(job.get("sample_unit") or "records")
        taps = _expected_tap_labels(job)
        count_text = ("%s %s" % (format(expected, ",d"), unit)) if expected else unit
        tap_text = ", ".join(taps) if taps else "the contract taps"
        requirements.append("%s: %s; taps: %s" % (label, count_text, tap_text))
        schema_path = _capture_schema_path(bundle, manifest, job, split)
        if not schema_path.is_file():
            problems.append("%s has not been captured (%s is missing)" % (label, schema_path))
            continue
        try:
            schema = load_strict_yaml_or_json(schema_path)
        except Exception as exc:
            problems.append("%s capture schema cannot be read: %s" % (label, exc))
            continue
        captured = int(schema.get("captured_samples") or 0)
        if expected and captured < expected:
            problems.append(
                "%s contains %s of %s required %s"
                % (label, format(captured, ",d"), format(expected, ",d"), unit)
            )
        missing = _missing_taps(schema, job)
        if missing:
            problems.append("%s is missing tap(s): %s" % (label, ", ".join(missing)))
    if not problems:
        return True
    action = "evaluate" if target_name == "evaluate.py" else "train"
