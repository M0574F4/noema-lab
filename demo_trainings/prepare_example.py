def _require_neural_receiver_capture_sweep(bundle: Path) -> None:
    """Require one consistent SNR-variant source in every frozen capture asset."""

    expected = tuple(float(value) for value in NEURAL_RECEIVER_CAPTURE_SNR_DB)
    source_path = bundle / "noema_recipe.yaml"
    if not source_path.is_file():
        raise ValueError(
            "The neural-receiver bundle is missing noema_recipe.yaml. "
            "Export the training bundle again before attaching the demo."
        )
    source_recipe = load_recipe(source_path)
