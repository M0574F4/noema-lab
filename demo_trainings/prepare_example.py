def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _mapping(path: Path) -> Dict[str, Any]:
    value = load_strict_yaml_or_json(path)
    if not isinstance(value, Mapping):
        raise ValueError("Expected a YAML object: %s" % path)
    return dict(value)


def _bundle_result(bundle: Path) -> Dict[str, Any]:
    manifest = _mapping(bundle / "project_manifest.yaml")
    if str(manifest.get("kind") or "") != "noema.training_interface_bundle@1":
        raise ValueError("Not a neutral Noema training-interface bundle: %s" % bundle)
    contract = _mapping(bundle / "training_contract.yaml")
    graph_contract = dict((manifest.get("contracts") or {}).get("scenario_graph") or {})
    slot_contract = dict((manifest.get("contracts") or {}).get("trainable_slots") or {})
    data_contract_path = bundle / "data_contract.yaml"
    return {
        "status": "exported",
        "kind": str(manifest.get("kind") or ""),
        "out_dir": str(bundle),
        "contract_id": str(contract.get("id") or ""),
        "contract_sha256": str(slot_contract.get("sha256") or ""),
        "contract_file_sha256": str(slot_contract.get("file_sha256") or _sha256(bundle / "training_contract.yaml")),
        "scenario_graph_sha256": str(graph_contract.get("sha256") or ""),
        "scenario_graph_file_sha256": str(graph_contract.get("file_sha256") or _sha256(bundle / "scenario_graph.json")),
        "project_manifest": manifest,
        "data_contract": _mapping(data_contract_path) if data_contract_path.is_file() else {},
        "files": [str(path.relative_to(bundle)) for path in bundle.rglob("*") if path.is_file()],
    }


def prepare_example(bundle: Path, demo: str, *, project_root: Path) -> Path:
    bundle = bundle.resolve()
    demo_id = str(demo or "").strip()
    if demo_id not in DEMO_LOSSES:
        raise ValueError("Unknown demo %r; choose one of %s" % (demo_id, ", ".join(sorted(DEMO_LOSSES))))
    _require_safe_demo_handoff_paths(bundle)
    recipe, training_plan = _load_planned_recipe(bundle)
    if not training_plan.selected_steps:
        raise ValueError("The exported training plan has no selected replacement blocks")
    registry = build_registry()
    if demo_id == "phase-tracking-receiver":
        recipe, training_plan, capture_enrichments = (
            _ensure_phase_tracking_demo_capture_plan(
                bundle,
                recipe,
                training_plan,
                registry=registry,
                project_root=project_root.resolve(),
            )
        )
        if capture_enrichments:
            additions = " and ".join(capture_enrichments)
            print(
                "phase-tracking demo updated its generated capture plan with %s; "
                "recapture train, validation, "
                "and held-out test before training." % additions
            )
    elif demo_id == "delayed-csi-resource-allocation":
        recipe, training_plan, capture_enrichments = (
            _ensure_delayed_csi_allocation_demo_capture_plan(
                bundle,
                recipe,
                training_plan,
                registry=registry,
                project_root=project_root.resolve(),
            )
        )
        if capture_enrichments:
            print(
                "delayed-CSI allocation demo added %s; recapture train, "
                "validation, and held-out test before training."
                % " and ".join(capture_enrichments)
            )
    options = ExportOptions(
        optimizable_steps=list(training_plan.selected_steps),
        loss=DEMO_LOSSES[demo_id],
        framework="torch",
        exporter=demo_id,
        project_root=project_root.resolve(),
        include_starter=True,
    )
    exporter = select_differentiable_exporter(recipe, registry, options)
    plan = exporter.build_plan(recipe, registry, options)
    if demo_id == "deepjscc-image":
        _ensure_deepjscc_demo_data_contract(
            bundle,
            plan,
            project_root=project_root.resolve(),
        )
    bundle_result = _bundle_result(bundle)
    _require_demo_signals(bundle_result, plan, demo_id)
    if demo_id == "neural-receiver":
        _require_neural_receiver_capture_sweep(bundle)
    elif demo_id == "phase-tracking-receiver":
        _require_phase_tracking_capture_sweep(bundle)
    training_project = bundle / "reference_training"
    starter_payload = exporter.write_export(
        plan,
        training_project,
        force=True,
    )
    _attach_optional_starter(
        bundle_result,
        starter_payload,
        destination=bundle,
        selected_exporter=exporter.id,
    )
    _write_root_demo_handoff(
        bundle,
        demo_id,
        project_root=project_root.resolve(),
    )
    return training_project


def _load_planned_recipe(bundle: Path) -> tuple[Any, Any]:
    """Rejoin the neutral scenario and its external training intent.

    Training-interface bundles deliberately store these separately.  Demo
    exporters need the transient joined view so they preserve researcher-chosen
    capture IDs instead of falling back to their suggested labels.
    """

    neutral_recipe = load_recipe(bundle / "noema_recipe.yaml")
    training_plan = load_training_plan(bundle / "training_plan.yaml")
    return apply_training_plan(neutral_recipe, training_plan), training_plan


def _ensure_phase_tracking_demo_capture_plan(
    bundle: Path,
    recipe: Any,
    training_plan: TrainingPlan,
    *,
    registry: Any,
    project_root: Path,
) -> tuple[Any, TrainingPlan, tuple[str, ...]]:
    """Add the reference demo's capture requirements after explicit attachment.

    The runnable scenario and generic Workbench remain neutral.  Invoking this
    specific demo is the point at which its auxiliary objective becomes known,
    so only the generated external training plan and Noema-owned capture assets
    are enriched.  Existing captured shards and researcher artifacts are never
    removed.
    """

    selected = set(training_plan.selected_steps)
    receivers = [
        step
        for step in recipe.steps
        if step.id in selected
        and step.op == "demodulation.phase_tracking_receiver_adapter"
    ]
    if len(receivers) != 1:
        return recipe, training_plan, ()
    phase_truth_reference = str(
        receivers[0].inputs.get("phase_truth") or ""
    ).strip()
    if not phase_truth_reference:
        return recipe, training_plan, ()

    capture = dict(training_plan.dataset_capture or {})
    raw_taps = capture.get("taps")
    if raw_taps is None:
        taps: list[Dict[str, Any]] = []
    elif isinstance(raw_taps, list):
        if any(not isinstance(item, Mapping) for item in raw_taps):
            raise ValueError(
                "training_plan.dataset_capture.taps entries must be objects"
            )
        taps = [dict(item) for item in raw_taps]
    else:
        raise ValueError("training_plan.dataset_capture.taps must be a list")
    phase_target_present = any(
        isinstance(item, Mapping)
        and str(item.get("from") or "") == phase_truth_reference
        for item in taps
    )
    additions: list[str] = []
    if not phase_target_present:
        existing_ids = {
            str(item.get("id") or "")
            for item in taps
            if isinstance(item, Mapping)
        }
        tap_id = _unique_demo_capture_tap_id(
            phase_truth_reference,
            existing_ids,
        )
        taps.append({"id": tap_id, "from": phase_truth_reference})
        capture["taps"] = taps
        additions.append("its training-only carrier-phase target")

    expected_sweep = tuple(float(value) for value in PHASE_TRACKING_CAPTURE_SNR_DB)
    canonical_matrix = canonicalize_recipe_matrix(recipe)
    matrix_snr = _finite_numeric_sequence(
        matrix_values_for_step_param(recipe, "wireless_channel", "snr_db")
    )
    raw_sweep = capture.get("sweep")
    if canonical_matrix.enabled:
        if matrix_snr != expected_sweep:
            rendered = "missing" if matrix_snr is None else repr(matrix_snr)
            raise ValueError(
                "The phase-tracking receiver demonstration requires the recipe "
                "matrix to define wireless_channel.snr_db = [-2, 2, 6, 10]; "
                "the source matrix declares %s." % rendered
            )
        if raw_sweep is not None:
            equivalent = (
                isinstance(raw_sweep, Mapping)
                and set(str(key) for key in raw_sweep)
                == {"wireless_channel.snr_db"}
                and _finite_numeric_sequence(
                    raw_sweep.get("wireless_channel.snr_db")
                )
                == expected_sweep
            )
            if not equivalent:
                raise ValueError(
                    "The phase-tracking receiver capture plan cannot combine its "
                    "recipe matrix with a different dataset_capture.sweep. Keep "
                    "metadata.matrix as the single SNR variant definition."
                )
            capture.pop("sweep", None)
            additions.append(
                "the recipe matrix as its single SNR variant definition"
            )
    elif raw_sweep is None:
        capture["sweep"] = {
            "wireless_channel.snr_db": [
                int(value) if float(value).is_integer() else float(value)
                for value in expected_sweep
            ]
        }
        additions.append("the SNR capture sweep [-2, 2, 6, 10]")
    elif isinstance(raw_sweep, Mapping):
        configured_snr = raw_sweep.get("wireless_channel.snr_db")
        if configured_snr is None:
            updated_sweep = dict(raw_sweep)
            updated_sweep["wireless_channel.snr_db"] = [
                int(value) if float(value).is_integer() else float(value)
                for value in expected_sweep
            ]
            capture["sweep"] = updated_sweep
            additions.append("the SNR capture sweep [-2, 2, 6, 10]")
        elif _finite_numeric_sequence(configured_snr) != expected_sweep:
            # Preserve researcher intent. The existing frozen-sweep validator
            # below will report the exact conflict without rewriting the bundle.
            return recipe, training_plan, ()
    else:
        # Ordered assignment sweeps are explicit researcher intent. The demo's
        # existing validator will explain that they do not match its benchmark.
        return recipe, training_plan, ()

    if not additions:
        return recipe, training_plan, ()
    enriched_plan = TrainingPlan(
        selected_steps=training_plan.selected_steps,
        loss_steps=training_plan.loss_steps,
        dataset_capture=capture,
        objective=training_plan.objective,
        starter=training_plan.starter,
        framework=training_plan.framework,
        extra_fields=training_plan.extra_fields,
    )
    enriched_recipe = apply_training_plan(recipe, enriched_plan)

    data = write_generic_capture_data_contract(
        enriched_recipe,
        registry,
        selected_step_ids=list(enriched_plan.selected_steps),
        out_dir=bundle,
        project_root=project_root,
    )
    training_plan_path = bundle / "training_plan.yaml"
    training_plan_path.write_text(
        yaml.safe_dump(enriched_plan.to_dict(), sort_keys=False),
        encoding="utf-8",
    )
    manifest_path = bundle / "project_manifest.yaml"
    manifest = _mapping(manifest_path)
    manifest["capture_jobs"] = list(data.get("capture_jobs") or [])
    contract = dict(data.get("data_contract") or {})
    manifest["data_contract"] = {
        "path": "data_contract.yaml",
        "kind": "noema.training_data_contract@1",
        "sha256": str(data.get("data_contract_sha256") or ""),
        "file_sha256": str(data.get("data_contract_file_sha256") or ""),
        "ownership": dict(contract.get("ownership") or {}),
    }
    manifest["training_plan"] = {
        "path": "training_plan.yaml",
        "sha256": training_plan_fingerprint(enriched_plan),
    }
    manifest_path.write_text(
        yaml.safe_dump(manifest, sort_keys=False),
        encoding="utf-8",
    )
    return enriched_recipe, enriched_plan, tuple(additions)


def _unique_demo_capture_tap_id(
    reference: str,
    existing_ids: set[str],
) -> str:
    base = "".join(
        character if character.isalnum() or character == "_" else "_"
        for character in str(reference)
    ).strip("_") or "phase_truth"
    candidate = base
    suffix = 2
    while candidate in existing_ids:
        candidate = "%s_%d" % (base, suffix)
        suffix += 1
    return candidate


def _ensure_delayed_csi_allocation_demo_capture_plan(
    bundle: Path,
    recipe: Any,
    training_plan: TrainingPlan,
    *,
    registry: Any,
    project_root: Path,
) -> tuple[Any, TrainingPlan, tuple[str, ...]]:
    """Attach the demo-only current-CSI outcome without changing the recipe.

    The allocator ABI itself requires only delayed transmitter CSI.  Invoking
    this optional example is the point where aligned current CSI becomes known
    as an auxiliary loss input, so it belongs in the generated training plan
    rather than in the portable model interface.
    """

    selected = set(training_plan.selected_steps)
    allocators = [
        step
        for step in recipe.steps
        if step.id in selected
        and step.op
        in {
            "model.symbol_power_allocator",
            "model.causal_csi_power_allocator",
        }
    ]
    if len(allocators) != 1:
        return recipe, training_plan, ()
    delayed_reference = str(
        allocators[0].inputs.get("channel_state") or ""
    ).strip()
    if "." not in delayed_reference:
        return recipe, training_plan, ()
    observation_id, observation_output = delayed_reference.split(".", 1)
    if observation_output != "transmitter_csi":
        return recipe, training_plan, ()
    observation = next(
        (step for step in recipe.steps if step.id == observation_id),
        None,
    )
    if observation is None or observation.op != "wireless.ofdm_delayed_csi":
        return recipe, training_plan, ()
    current_reference = "%s.actual_state" % observation.id

    capture = dict(training_plan.dataset_capture or {})
    raw_taps = capture.get("taps")
    if raw_taps is None:
        taps: list[Dict[str, Any]] = []
    elif isinstance(raw_taps, list):
        if any(not isinstance(item, Mapping) for item in raw_taps):
            raise ValueError(
                "training_plan.dataset_capture.taps entries must be objects"
            )
        taps = [dict(item) for item in raw_taps]
    else:
        raise ValueError("training_plan.dataset_capture.taps must be a list")

    if any(
        str(item.get("from") or "") == current_reference for item in taps
    ):
        return recipe, training_plan, ()
    tap_id = _unique_demo_capture_tap_id(
        current_reference,
        {
            str(item.get("id") or "")
            for item in taps
            if isinstance(item, Mapping)
        },
    )
    taps.append({"id": tap_id, "from": current_reference})
    capture["taps"] = taps
    enriched_plan = TrainingPlan(
        selected_steps=training_plan.selected_steps,
        loss_steps=training_plan.loss_steps,
        dataset_capture=capture,
        objective=training_plan.objective,
        starter=training_plan.starter,
        framework=training_plan.framework,
        extra_fields=training_plan.extra_fields,
    )
    enriched_recipe = apply_training_plan(recipe, enriched_plan)
    data = write_generic_capture_data_contract(
        enriched_recipe,
        registry,
        selected_step_ids=list(enriched_plan.selected_steps),
        out_dir=bundle,
        project_root=project_root,
    )

    training_plan_path = bundle / "training_plan.yaml"
    training_plan_path.write_text(
        yaml.safe_dump(enriched_plan.to_dict(), sort_keys=False),
        encoding="utf-8",
    )
    manifest_path = bundle / "project_manifest.yaml"
    manifest = _mapping(manifest_path)
    manifest["capture_jobs"] = list(data.get("capture_jobs") or [])
    contract = dict(data.get("data_contract") or {})
    manifest["data_contract"] = {
        "path": "data_contract.yaml",
        "kind": "noema.training_data_contract@1",
        "sha256": str(data.get("data_contract_sha256") or ""),
        "file_sha256": str(data.get("data_contract_file_sha256") or ""),
        "ownership": dict(contract.get("ownership") or {}),
    }
    manifest["training_plan"] = {
        "path": "training_plan.yaml",
        "sha256": training_plan_fingerprint(enriched_plan),
    }
    manifest_path.write_text(
        yaml.safe_dump(manifest, sort_keys=False),
        encoding="utf-8",
    )
    return (
        enriched_recipe,
        enriched_plan,
        ("its aligned training-only current-CSI outcome",),
    )


def _require_safe_demo_handoff_paths(bundle: Path) -> None:
    """Refuse to replace root files that were not created by this helper."""

    for relative in DEMO_HANDOFF_FILES:
        path = bundle / relative
        if not path.exists():
            continue
        if not path.is_file():
            raise ValueError(
                "Cannot attach the demo because %s exists and is not a regular file" % path
            )
        try:
            existing = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            raise ValueError(
                "Cannot verify ownership of existing demo handoff file %s" % path
            ) from exc
        if DEMO_HANDOFF_MARKER not in existing[:512]:
            raise ValueError(
                "Refusing to overwrite researcher-owned file %s. Rename it or choose a "
                "different bundle directory before attaching the published demo." % path
            )


