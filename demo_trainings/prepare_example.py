def _require_demo_signals(bundle_result: Mapping[str, Any], plan: Any, demo: str) -> None:
    """Validate only the checked-in example's needs, never the generic contract."""

    expected: list[str] = []
    if demo == "resource-allocation":
        expected = [str(plan.feature_reference)]
    elif demo == "delayed-csi-resource-allocation":
        expected = [
            str(plan.delayed_csi_reference),
            str(plan.current_csi_reference),
        ]
    elif demo == "csi-feedback":
        expected = [str(plan.true_csi_reference)]
    elif demo == "mimo-ofdm-channel-estimation":
        expected = [
            str(plan.pilot_reference),
            str(plan.mask_reference),
            str(plan.feature_reference),
            str(plan.noise_reference),
            str(plan.target_reference),
        ]
    elif demo == "phase-tracking-receiver":
        expected = [
            str(plan.feature_reference),
            str(plan.pilot_context_reference),
            str(plan.target_reference),
        ]
    elif demo in {"neural-receiver", "modulation-recognition"}:
        expected = [str(plan.feature_reference), str(plan.target_reference)]
